import * as React from "react";
import { cn } from "@/lib/utils";

const Card = React.forwardRef<HTMLDivElement, React.HTMLAttributes<HTMLDivElement>>(
  ({ className, ...props }, ref) => (
    <div
      ref={ref}
      className={cn(
        "rounded-lg border border-jx-border bg-jx-card text-jx-text",
        // Subtle two-layer shadow gives hairline depth on white surfaces
        // without ever reading dark.
        "shadow-[0_1px_0_rgba(17,17,17,0.02),0_2px_6px_-2px_rgba(17,17,17,0.05)]",
        // Soft inner highlight at the top of the card for a printed-paper feel.
        "[--jx-card-highlight:linear-gradient(180deg,rgba(255,255,255,1)_0%,rgba(252,252,252,1)_100%)]",
        "bg-[image:var(--jx-card-highlight)]",
        className
      )}
      {...props}
    />
  )
);
Card.displayName = "Card";

const CardHeader = React.forwardRef<HTMLDivElement, React.HTMLAttributes<HTMLDivElement>>(
  ({ className, ...props }, ref) => (
    <div
      ref={ref}
      className={cn("flex flex-col space-y-1.5 p-5", className)}
      {...props}
    />
  )
);
CardHeader.displayName = "CardHeader";

